import fs from 'node:fs';
import path from 'node:path';
var FIREBASE_SW_FILE = 'firebase-messaging-sw.js';
var buildServiceWorker = function () {
    var config = {
        apiKey: process.env.VITE_FIREBASE_API_KEY || '',
        authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN || '',
        projectId: process.env.VITE_FIREBASE_PROJECT_ID || '',
        storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET || '',
        messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
        appId: process.env.VITE_FIREBASE_APP_ID || '',
    };
    return "/* eslint-disable */\n// Generated by Vite. Client Firebase config only \u2014 never put Admin secrets here.\nimportScripts('https://www.gstatic.com/firebasejs/12.17.1/firebase-app-compat.js')\nimportScripts('https://www.gstatic.com/firebasejs/12.17.1/firebase-messaging-compat.js')\n\nconst firebaseConfig = ".concat(JSON.stringify(config, null, 2), ";\nconst isConfigured = Object.values(firebaseConfig).every(Boolean);\n\nif (isConfigured && !firebase.apps.length) {\n  firebase.initializeApp(firebaseConfig);\n}\n\nconst messaging = isConfigured ? firebase.messaging() : null;\n\nconst buildNotificationOptions = (payload) => {\n  const data = payload.data || {};\n  const title = (payload.notification && payload.notification.title) || data.title || 'Drivoo';\n  const body = (payload.notification && payload.notification.body) || data.body || '';\n  return {\n    title,\n    options: {\n      body,\n      data: {\n        url: data.url || '/',\n        type: data.type || '',\n      },\n      tag: data.tag || 'drivoo-fcm',\n      renotify: false,\n    },\n  };\n};\n\nif (messaging) {\n  messaging.onBackgroundMessage((payload) => {\n    // FCM already displays messages that include a notification payload.\n    if (payload.notification) {\n      return;\n    }\n    const { title, options } = buildNotificationOptions(payload);\n    return self.registration.showNotification(title, options);\n  });\n}\n\nself.addEventListener('notificationclick', (event) => {\n  event.notification.close();\n  const targetUrl = (event.notification.data && event.notification.data.url) || '/';\n  event.waitUntil((async () => {\n    const windowClients = await clients.matchAll({ type: 'window', includeUncontrolled: true });\n    for (const client of windowClients) {\n      if ('focus' in client) {\n        await client.focus();\n        if ('navigate' in client && targetUrl) {\n          await client.navigate(targetUrl);\n        }\n        return;\n      }\n    }\n    if (clients.openWindow) {\n      await clients.openWindow(targetUrl);\n    }\n  })());\n});\n");
};
export var firebaseMessagingSwPlugin = function () {
    var writeDevFile = function () {
        var publicDir = path.resolve(process.cwd(), 'public');
        if (!fs.existsSync(publicDir)) {
            fs.mkdirSync(publicDir, { recursive: true });
        }
        fs.writeFileSync(path.join(publicDir, FIREBASE_SW_FILE), buildServiceWorker());
    };
    return {
        name: 'firebase-messaging-sw',
        configureServer: function (server) {
            writeDevFile();
            server.middlewares.use(function (req, res, next) {
                var _a;
                if (((_a = req.url) === null || _a === void 0 ? void 0 : _a.split('?')[0]) !== "/".concat(FIREBASE_SW_FILE)) {
                    next();
                    return;
                }
                res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
                res.setHeader('Service-Worker-Allowed', '/');
                res.end(buildServiceWorker());
            });
        },
        generateBundle: function () {
            this.emitFile({
                type: 'asset',
                fileName: FIREBASE_SW_FILE,
                source: buildServiceWorker(),
            });
        },
    };
};
